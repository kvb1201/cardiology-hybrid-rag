class CohereEvaluatorClient:
    """HTTP client for Cohere Chat API v2 downstream evaluation."""

    def __init__(
        self,
        api_key: Optional[str] = None,
        model: str = "command-r-08-2024",
        temperature: float = 0.0,
        max_tokens: int = 512,
        timeout_seconds: int = 90,
        retry_config: Optional[dict] = None,
    ):
        self.api_key = api_key or os.environ.get("COHERE_API_KEY", "")
        if not self.api_key:
            raise ValueError("COHERE_API_KEY is not configured in the environment.")
        self.model = model
        self.temperature = temperature
        self.max_tokens = max_tokens
        self.timeout_seconds = timeout_seconds

        rc = retry_config or {}
        self.max_retries = rc.get("max_retries", 3)
        self.initial_delay = rc.get("initial_delay_seconds", 3.0)
        self.backoff_factor = rc.get("backoff_factor", 2.0)
        self.max_delay = rc.get("max_delay_seconds", 15.0)

    def evaluate(
        self,
        query_text: str,
        generated_answer: str,
        reference_evidence_text: str,
    ) -> Dict[str, Any]:
        """
        Evaluate a single generated answer against reference evidence.
        Returns parsed validation dictionary with scores, rationales, tokens, latency.
        """
        import requests

        system_prompt, user_prompt = build_evaluator_prompt(
            query_text=query_text,
            generated_answer=generated_answer,
            reference_evidence_text=reference_evidence_text,
        )

        headers = {
            "Authorization": f"Bearer {self.api_key}",
            "Content-Type": "application/json",
        }

        payload = {
            "model": self.model,
            "messages": [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt},
            ],
            "temperature": self.temperature,
            "max_tokens": self.max_tokens,
            "response_format": COHERE_EVALUATOR_SCHEMA,
        }

        last_error = None
        for attempt in range(self.max_retries + 1):
            t0 = time.time()
            try:
                resp = requests.post(
                    COHERE_CHAT_URL,
                    headers=headers,
                    json=payload,
                    timeout=self.timeout_seconds,
                )
                dt = time.time() - t0

                if resp.status_code == 200:
                    data = resp.json()
                    usage = data.get("usage", {})
                    content = data.get("message", {}).get("content", [])
                    raw_text = "".join([c.get("text", "") for c in content if c.get("type") == "text"])

                    parsed = validate_evaluator_response(raw_text)
                    parsed["latency_seconds"] = round(dt, 2)
                    parsed["usage"] = usage
                    parsed["trial_call_remaining"] = resp.headers.get("x-trial-endpoint-call-remaining")
                    parsed["monthly_limit"] = resp.headers.get("x-endpoint-monthly-call-limit")
                    return parsed

                elif resp.status_code == 429:
                    # Check if monthly trial quota exceeded
                    err_body = resp.text.lower()
                    if "monthly" in err_body or "trial key monthly call limit" in err_body:
                        raise MonthlyQuotaExceededError(
                            "Cohere trial monthly call limit (1,000 calls) has been exhausted."
                        )
                    last_error = RuntimeError(f"Rate limited (429): {resp.text}")

                elif resp.status_code in (500, 502, 503, 504):
                    last_error = RuntimeError(f"Server error ({resp.status_code}): {resp.text}")

                else:
                    raise EvaluatorError(f"Cohere API error ({resp.status_code}): {resp.text}")

            except (requests.exceptions.RequestException, RuntimeError) as exc:
                last_error = exc

            if attempt < self.max_retries:
                delay = min(self.initial_delay * (self.backoff_factor ** attempt), self.max_delay)
                logger.warning(
                    "Cohere call failed (attempt %d/%d): %s. Retrying in %.1fs...",
                    attempt + 1,
                    self.max_retries,
                    last_error,
                    delay,
                )
                time.sleep(delay)

        raise EvaluatorError(f"Cohere evaluation failed after {self.max_retries} retries: {last_error}")


class MockEvaluatorClient:
    """Mock evaluator client for offline testing and deterministic dry-runs."""

    def __init__(self, model: str = "mock-evaluator", temperature: float = 0.0):
        self.model = model
        self.temperature = temperature

    def evaluate(
        self,
        query_text: str,
        generated_answer: str,
        reference_evidence_text: str,
    ) -> Dict[str, Any]:
        """Compute deterministic mock evaluation scores based on content length/overlap."""
        # Simple deterministic heuristic for test stability
        q_words = set(query_text.lower().split())
        a_words = set(generated_answer.lower().split())
        e_words = set(reference_evidence_text.lower().split())

        cov = round(min(1.0, max(0.2, len(a_words & e_words) / max(1, min(len(e_words), 30)))), 2)
        con = 0.85 if len(generated_answer) > 20 else 0.40
        rel = round(min(1.0, max(0.3, len(a_words & q_words) / max(1, len(q_words)))), 2)
        comp = round((cov + con + rel) / 3.0, 4)

        return {
            "scores": {
                "evidence_coverage": cov,
                "factual_consistency": con,
                "answer_relevance": rel,
                "composite_quality": comp,
            },
            "rationales": {
                "evidence_coverage": f"Mock rationale: covered {cov * 100:.0f}% of evidence concepts.",
                "factual_consistency": f"Mock rationale: consistency scored at {con:.2f}.",
                "answer_relevance": f"Mock rationale: relevance scored at {rel:.2f}.",
            },
            "latency_seconds": 0.01,
            "usage": {"tokens": {"input_tokens": 100, "output_tokens": 50}},
            "trial_call_remaining": "99",
            "monthly_limit": "1000",
        }


