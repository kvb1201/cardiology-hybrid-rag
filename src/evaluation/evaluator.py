class DownstreamEvaluator:
    """Orchestrator for running downstream evaluations across experiment conditions."""

    def __init__(
        self,
        config: Optional[dict] = None,
        client: Optional[Any] = None,
        use_mock: bool = False,
    ):
        self.config = config or load_evaluator_config()
        self.provider = self.config.get("provider", "cohere")
        self.model = self.config.get("model", "command-r-08-2024")
        self.temperature = float(self.config.get("temperature", 0.0))
        self.max_tokens = int(self.config.get("max_output_tokens", 350))
        self.request_delay = 0.0 if use_mock else float(self.config.get("request_delay_seconds", 3.5))

        if client:
            self.client = client
        elif use_mock:
            self.client = MockEvaluatorClient(model=f"mock-{self.model}", temperature=self.temperature)
        else:
            self.client = CohereEvaluatorClient(
                model=self.model,
                temperature=self.temperature,
                max_tokens=self.max_tokens,
                retry_config=self.config.get("retry"),
            )

    def evaluate_condition(
        self,
        query_id: str,
        retriever: str,
        k: int,
        query_text: str,
        generated_answer: str,
        reference_evidence_text: str,
    ) -> Dict[str, Any]:
        """Evaluate a single experimental condition."""
        eval_result = self.client.evaluate(
            query_text=query_text,
            generated_answer=generated_answer,
            reference_evidence_text=reference_evidence_text,
        )

        record = {
            "query_id": query_id,
            "retriever": retriever,
            "k": k,
            "scores": eval_result["scores"],
            "rationales": eval_result["rationales"],
            "evaluator_provider": self.provider,
            "evaluator_model": self.model,
            "prompt_version": self.config.get("evaluator_prompt_version", "v1.0"),
            "latency_seconds": eval_result.get("latency_seconds", 0.0),
            "tokens": eval_result.get("usage", {}).get("tokens", {}),
            "status": "success",
            "timestamp_utc": datetime.now(timezone.utc).isoformat(),
        }
        return record

    def run(
        self,
        conditions: List[Tuple[str, str, int]],
        output_path: Path | str,
        reference_evidence_path: Path | str = DEFAULT_REFERENCE_EVIDENCE_PATH,
        generated_answers_path: Path | str = DEFAULT_GENERATED_ANSWERS_PATH,
    ) -> Dict[str, Any]:
        """
        Run evaluations across the given list of conditions.
        Skips conditions already successfully completed in output_path.
        """
        evidence_map = load_reference_evidence_map(reference_evidence_path)
        answers_map = load_generated_answers(generated_answers_path)
        completed_keys = load_completed_evaluations(output_path)

        total_conditions = len(conditions)
        skipped = 0
        succeeded = 0
        failed = 0

        logger.info(
            "Starting downstream evaluation: total=%d, previously_completed=%d",
            total_conditions,
            len(completed_keys),
        )

        for idx, (qid, retriever, k) in enumerate(conditions, 1):
            key = (qid, retriever, k)
            if key in completed_keys:
                skipped += 1
                continue

            if qid not in evidence_map:
                logger.error("Query %s not found in reference evidence map! Skipping.", qid)
                failed += 1
                continue

            if key not in answers_map:
                logger.error("Condition %s not found in generated answers! Skipping.", key)
                failed += 1
                continue

            q_info = evidence_map[qid]
            ans_rec = answers_map[key]

            query_text = q_info["query_text"]
            reference_evidence_text = q_info["evidence_text"]
            generated_answer = ans_rec["generated_answer"]

            try:
                rec = self.evaluate_condition(
                    query_id=qid,
                    retriever=retriever,
                    k=k,
                    query_text=query_text,
                    generated_answer=generated_answer,
                    reference_evidence_text=reference_evidence_text,
                )
                append_evaluation_record(rec, output_path)
                completed_keys.add(key)
                succeeded += 1

                cov = rec["scores"]["evidence_coverage"]
                con = rec["scores"]["factual_consistency"]
                rel = rec["scores"]["answer_relevance"]
                comp = rec["scores"]["composite_quality"]
                lat = rec["latency_seconds"]

                logger.info(
                    "[%d/%d] %s | %s | K=%d | Cov=%.2f Con=%.2f Rel=%.2f Comp=%.2f (%.1fs)",
                    idx,
                    total_conditions,
                    qid,
                    retriever,
                    k,
                    cov,
                    con,
                    rel,
                    comp,
                    lat,
                )

            except Exception as exc:
                logger.error("Failed evaluation for condition %s: %s", key, exc)
                failed += 1
                # Record failure explicitly
                fail_rec = {
                    "query_id": qid,
                    "retriever": retriever,
                    "k": k,
                    "status": "error",
                    "error_type": type(exc).__name__,
                    "error_message": str(exc),
                    "evaluator_provider": self.provider,
                    "evaluator_model": self.model,
                    "timestamp_utc": datetime.now(timezone.utc).isoformat(),
                }
                append_evaluation_record(fail_rec, output_path)

                if isinstance(exc, MonthlyQuotaExceededError):
                    logger.critical("Monthly quota exceeded. Terminating evaluation loop.")
                    break

            if idx < total_conditions and self.request_delay > 0:
                time.sleep(self.request_delay)

        return {
            "total_conditions": total_conditions,
            "skipped": skipped,
            "succeeded": succeeded,
            "failed": failed,
            "total_completed": len(completed_keys),
        }
