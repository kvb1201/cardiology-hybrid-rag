SYSTEM_PROMPT_V1 = """\
You are an impartial automated evaluator assessing the quality of answers generated by a retrieval-augmented generation (RAG) system in cardiovascular medicine.

You must evaluate the Generated Answer against the Reference Evidence and the Clinical Query along exactly three dimensions:
1. evidence_coverage (0.0 to 1.0): How completely the generated answer addresses the key facts and clinical information supported by the provided reference evidence that are relevant to answering the query.
2. factual_consistency (0.0 to 1.0): Whether claims in the generated answer are supported by the provided reference evidence, without unsupported additions, contradictions, or fabricated facts (penalize ungrounded statements or hallucinations).
3. answer_relevance (0.0 to 1.0): How directly, appropriately, and completely the generated answer addresses the clinical query using the available evidence.

Important Guidelines:
- Reason strictly and solely from the provided Reference Evidence and Clinical Query.
- Do not use external medical knowledge to verify claims beyond the provided evidence.
- You are evaluating automated answer quality relative to the provided evidence, NOT general clinical correctness or clinical advice validity.
- Do not attempt to judge or speculate about the retrieval system or generator model.
- Assign numeric scores between 0.0 and 1.0 for each dimension.
- Provide a concise rationale for each score explaining your assessment.
- Respond strictly with a valid JSON object matching the required schema.\
"""

USER_PROMPT_TEMPLATE_V1 = """\
### Clinical Query:
{query_text}

### Reference Evidence:
{reference_evidence_text}

### Generated Answer:
{generated_answer_text}

Evaluate the generated answer based strictly on the reference evidence and clinical query. Output valid JSON matching the schema.\
"""

# JSON schema for Cohere v2 Chat structured outputs
COHERE_EVALUATOR_SCHEMA = {
    "type": "json_object",
    "schema": {
        "type": "object",
        "properties": {
            "evidence_coverage": {
                "type": "number",
                "description": "Evidence coverage score between 0.0 and 1.0."
            },
            "factual_consistency": {
                "type": "number",
                "description": "Factual consistency score between 0.0 and 1.0."
            },
            "answer_relevance": {
                "type": "number",
                "description": "Answer relevance score between 0.0 and 1.0."
            },
            "rationales": {
                "type": "object",
                "properties": {
                    "evidence_coverage": {"type": "string"},
                    "factual_consistency": {"type": "string"},
                    "answer_relevance": {"type": "string"}
                },
                "required": ["evidence_coverage", "factual_consistency", "answer_relevance"]
            }
        },
        "required": ["evidence_coverage", "factual_consistency", "answer_relevance", "rationales"]
    }
}


def load_evaluator_config(config_path: Path | str | None = None) -> dict:
    """Load evaluator YAML configuration file."""
    path = Path(config_path) if config_path else DEFAULT_CONFIG_PATH
    if not path.exists():
        raise FileNotFoundError(f"Evaluator config not found at: {path}")
    with open(path, "r", encoding="utf-8") as f:
        data = yaml.safe_load(f)
    return data.get("evaluator", {})


def format_reference_evidence_text(chunks: List[Any]) -> str:
    """
    Format reference evidence chunks into plain numbered passages for the evaluator.
    Strips away all chunk IDs, document IDs, ranks, retrieval scores, and qrels grades
    to maintain strict blindness.
    """
    if not chunks:
        return "[No reference evidence provided]"

    passages = []
    for idx, c in enumerate(chunks, 1):
        if isinstance(c, dict):
            text = c.get("text") or c.get("chunk_text") or ""
        elif isinstance(c, str):
            text = c
        else:
            text = str(c)
        text = text.strip()
        if text:
            passages.append(f"Passage {idx}:\n{text}")

    if not passages:
        return "[No reference evidence provided]"
    return "\n\n---\n\n".join(passages)


def build_evaluator_prompt(
    query_text: str,
    generated_answer: str,
    reference_evidence_text: str,
    system_prompt_version: str = "v1.0",
    user_prompt_version: str = "v1.0",
) -> Tuple[str, str]:
    """
    Construct the system and user prompts for the downstream evaluator.

    Guarantees:
      - ONLY query_text, generated_answer, and reference_evidence_text are inserted.
      - Zero retriever identity, cutoff K, or generation metadata is exposed.
    """
    if system_prompt_version != "v1.0":
        raise ValueError(f"Unsupported system prompt version: {system_prompt_version}")
    if user_prompt_version != "v1.0":
        raise ValueError(f"Unsupported user prompt version: {user_prompt_version}")

    user_prompt = USER_PROMPT_TEMPLATE_V1.format(
        query_text=query_text.strip(),
        reference_evidence_text=reference_evidence_text.strip(),
        generated_answer_text=generated_answer.strip(),
    )
    return SYSTEM_PROMPT_V1, user_prompt


def validate_evaluator_response(raw_text: str) -> Dict[str, Any]:
    """
    Parse and validate the JSON output from the evaluator.
    Programmatically calculates composite_quality = mean(coverage, consistency, relevance).
    """
    cleaned = raw_text.strip()
    if cleaned.startswith("```json"):
        cleaned = cleaned[7:]
    elif cleaned.startswith("```"):
        cleaned = cleaned[3:]
    if cleaned.endswith("```"):
        cleaned = cleaned[:-3]
    cleaned = cleaned.strip()

    try:
        data = json.loads(cleaned)
    except json.JSONDecodeError as exc:
        raise SchemaValidationError(f"Invalid JSON from evaluator: {exc}\nRaw: {raw_text[:200]}") from exc

    if not isinstance(data, dict):
        raise SchemaValidationError(f"Evaluator output must be a JSON object, got {type(data)}")

    # Required primary fields
    required_dimensions = ["evidence_coverage", "factual_consistency", "answer_relevance"]
    for dim in required_dimensions:
        if dim not in data:
            raise SchemaValidationError(f"Missing required dimension: '{dim}'")
        val = data[dim]
        if not isinstance(val, (int, float)):
            raise SchemaValidationError(f"Dimension '{dim}' must be numeric, got {type(val)}: {val}")
        if val < 0.0 or val > 1.0:
            raise SchemaValidationError(f"Dimension '{dim}' score {val} outside valid range [0.0, 1.0]")

    cov = float(data["evidence_coverage"])
    con = float(data["factual_consistency"])
    rel = float(data["answer_relevance"])

    # Programmatic composite calculation (never trust model's composite arithmetic)
    composite = round((cov + con + rel) / 3.0, 4)

    # Validate rationales
    rationales = data.get("rationales", {})
    if not isinstance(rationales, dict):
        # Fallback if rationales was provided at top-level or as single rationale
        if "rationale" in data and isinstance(data["rationale"], str):
            single_rat = data["rationale"]
            rationales = {
                "evidence_coverage": single_rat,
                "factual_consistency": single_rat,
                "answer_relevance": single_rat,
            }
        else:
            rationales = {dim: "" for dim in required_dimensions}

    for dim in required_dimensions:
        if dim not in rationales or not isinstance(rationales[dim], str):
            rationales[dim] = str(rationales.get(dim, ""))

    return {
        "scores": {
            "evidence_coverage": cov,
            "factual_consistency": con,
            "answer_relevance": rel,
            "composite_quality": composite,
        },
        "rationales": {
            "evidence_coverage": rationales.get("evidence_coverage", "").strip(),
            "factual_consistency": rationales.get("factual_consistency", "").strip(),
            "answer_relevance": rationales.get("answer_relevance", "").strip(),
        },
    }


def load_reference_evidence_map(path: Path | str) -> Dict[str, Dict[str, Any]]:
    """Load reference evidence mapped by query_id."""
    p = Path(path)
    if not p.exists():
        raise FileNotFoundError(f"Reference evidence file not found at: {p}")
    with open(p, "r", encoding="utf-8") as f:
        data = json.load(f)

    qlist = data.get("queries", [])
    result = {}
    for q in qlist:
        qid = q["query_id"]
        qtext = q.get("query_text", "")
        chunks = q.get("reference_evidence", [])
        evidence_text = format_reference_evidence_text(chunks)
        result[qid] = {
            "query_text": qtext,
            "evidence_text": evidence_text,
            "topic": q.get("topic", "unspecified"),
            "n_evidence_chunks": len(chunks),
            "grade_2_available": q.get("grade_2_available", True),
        }
    return result


def load_generated_answers(path: Path | str) -> Dict[Tuple[str, str, int], Dict[str, Any]]:
    """Load successful generated answers mapped by (query_id, retriever, k)."""
    p = Path(path)
    if not p.exists():
        raise FileNotFoundError(f"Generated answers file not found at: {p}")
    answers = {}
    with open(p, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                rec = json.loads(line)
            except json.JSONDecodeError:
                continue
            if rec.get("status") == "success":
                key = (rec["query_id"], rec["retriever"], int(rec["k"]))
                # Keep latest success if multiple exist
                answers[key] = rec
    return answers


def load_completed_evaluations(path: Path | str) -> Set[Tuple[str, str, int]]:
    """Load completed evaluation conditions mapped by (query_id, retriever, k)."""
    p = Path(path)
    if not p.exists():
        return set()
    completed = set()
    with open(p, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                rec = json.loads(line)
            except json.JSONDecodeError:
                continue
            if rec.get("status") == "success":
                key = (rec["query_id"], rec["retriever"], int(rec["k"]))
                completed.add(key)
    return completed


def append_evaluation_record(record: Dict[str, Any], output_path: Path | str) -> None:
    """Atomically append a single evaluation record to the output JSONL file."""
    p = Path(output_path)
    p.parent.mkdir(parents=True, exist_ok=True)
    with open(p, "a", encoding="utf-8") as f:
        f.write(json.dumps(record, ensure_ascii=False) + "\n")


