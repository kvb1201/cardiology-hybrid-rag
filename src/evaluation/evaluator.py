"""
evaluator.py
------------
Downstream LLM Evaluator for the Cardiology-Chat research study.

Research Question:
  "How well do conventional retrieval metrics predict evidence sufficiency
   and downstream answer correctness in cardiovascular RAG?"

Methodological Controls & Blindness:
  - The evaluator model is from an independent family (Cohere Command R)
    to prevent self-evaluation bias relative to the generator (Google Gemini Flash-Lite).
  - Evaluator is strictly BLIND:
      * Receives ONLY: 1. Clinical Query, 2. Generated Answer, 3. Reference Evidence text.
      * NEVER receives: retriever identity, K cutoff value, retrieval ranks,
        retrieval scores, qrels relevance grades, retrieval metrics, or generator model name.
  - Primary evaluation dimensions:
      1. Evidence Coverage (0.0 to 1.0)
      2. Factual Consistency (0.0 to 1.0)
      3. Answer Relevance (0.0 to 1.0)
  - Composite quality is computed PROGRAMMATICALLY:
      composite_quality = (evidence_coverage + factual_consistency + answer_relevance) / 3.0
    The LLM's own arithmetic is never trusted.

Reference Evidence Caveat:
  Reference evidence is qrels-derived and therefore shares a reference dependency
  with conventional retrieval metrics. It is NOT independent clinician-authored ground truth.
  The evaluation assesses automated answer quality against provided evidence,
  NOT clinical correctness or clinical advice validity.
"""

